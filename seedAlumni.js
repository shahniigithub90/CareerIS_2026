    const defaultPassword = await bcrypt.hash('JUW@Alumni2026', 12);
    let inserted = 0, skipped = 0;

    for (const a of alumni) {
        // Build a unique email from name
        const emailBase = a.name
            .toLowerCase()
            .replace(/[^a-z0-9\s]/g, '')
            .trim()
            .replace(/\s+/g, '.')
            .substring(0, 40);
        const email = `${emailBase}.${a.graduationYear}@juw.edu.pk`;

        const existing = await mongoose.connection.db.collection('users').findOne({ email });
        if (existing) { skipped++; continue; }

        await mongoose.connection.db.collection('users').insertOne({
            name:           a.name,
            email,
            password:       defaultPassword,
            role:           'alumni',
            graduationYear: a.graduationYear,
            company:        a.company,
            designation:    'Software Engineer',
            department:     'Computer Science',
            isApproved:     true,
            isActive:       true,
            profilePicture: '',
            createdAt:      new Date()
        });
        inserted++;
    }

    console.log(`\n✅ Done! Inserted: ${inserted} alumni | Skipped (already exist): ${skipped}`);
    console.log(`📌 Default login password for all alumni: JUW@Alumni2026`);
    await mongoose.disconnect();
